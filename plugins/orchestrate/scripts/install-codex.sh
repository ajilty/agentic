#!/usr/bin/env bash
# install-codex.sh — compile the portable orchestrate skill into Codex CLI.
#   ./install-codex.sh [--scope user|project] [--dir <path>]
#   user (default): ~/.codex (or $CODEX_HOME)    project: ./.codex
#
# All harness mapping lives in scripts/harness-lib/ (ADR-0037); this driver names
# the orchestrate paths, emits the persona TOMLs, and prints the operator summary. HARNESS_LIB overrides the lib location for tmp copies.
set -euo pipefail

PLUGIN_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SKILL_DIR="$PLUGIN_ROOT/skills/orchestrate"
AGENTS="$SKILL_DIR/references/agents.yaml"
LIB="${HARNESS_LIB:-$(cd "$PLUGIN_ROOT/../.." && pwd)/scripts/harness-lib}"
. "$LIB/common.sh"; . "$LIB/codex.sh"
# Web is BUILT IN to codex (native Responses `web_search`, on by default).
# ORCHESTRATE_WEB_MCP is an ESCAPE HATCH only: set it to wire a custom web/doc MCP
# server name into the researcher role instead of using the built-in tool.
WEB_MCP="${ORCHESTRATE_WEB_MCP:-}"
parse_scope_args "$@"

case "$SCOPE" in
  user)    DEST="${OVERRIDE:-${CODEX_HOME:-$HOME/.codex}}" ;;
  project) DEST="${OVERRIDE:-$PWD/.codex}" ;;
  *) echo "scope must be user|project" >&2; exit 64 ;;
esac
require_yq4

# Skill-native install (ADR-0034): codex reads Agent Skills from .agents/skills
# (repo) / ~/.agents/skills (user) — SKILL.md + references/ + runtime/ land there
# as ONE copy; $CODEX_HOME keeps only the agent TOMLs. No AGENTS.md concatenation.
resolve_skills_root
SKILL_DEST="$SKILLS_ROOT/orchestrate"
AGENTS_DEST="$DEST/agents"; RT_DEST="$SKILL_DEST/runtime"

mkdir -p "$AGENTS_DEST"
# Codex dispatch addendum. SKILL.md is harness-neutral; this block, appended only to
# the generated Codex skill copy, says where the runtime lives and how to dispatch.
install_skill "$SKILL_DEST" <<BRAINADD

<!-- Codex dispatch addendum (generated by install-codex.sh; ADR-0034/0040) -->
## Codex: runtime location and how to dispatch a persona

Runtime helpers live in THIS skill's directory. First Bash action of the session:

    export PATH="$RT_DEST:\$PATH"

so \`ledger.sh\` / \`adr.sh\` resolve by bare name (ADR-0018).

Dispatch personas natively (\`spawn_agent\` or the equivalent); the installed agent
definitions carry each persona's sandbox and instructions. A writer works in its own git
worktree, created from the integration base before dispatch. Read each persona's result
from its scoped disk path (the disk-first read lane).
BRAINADD

for p in $(personas); do
  desc="$(p_desc "$p")"; sandbox="$(codex_sandbox "$p")"
  web="$(p_cap "$p" web)"
  model="$(codex_model "$(p_tier "$p" model)")"
  effort="$(codex_effort "$(p_tier "$p" effort)")"
  {
    printf 'name = "%s"\n' "$p"
    printf 'description = "%s"\n' "${desc//\"/\\\"}"
    printf 'sandbox_mode = "%s"\n' "$sandbox"
    [ -n "$model" ]  && printf 'model = "%s"\n' "$model"                       # only when the operator set one (ADR-0041)
    [ -n "$effort" ] && printf 'model_reasoning_effort = "%s"\n' "$effort"     # tier -> reasoning effort, passed through
    # Persona body, with its craft skill inlined (persona_prompt), goes in
    # developer_instructions (NOT `instructions`). Emit ALL root-level keys (incl. this
    # one) BEFORE any [table] header below, or the table would capture them. A TOML
    # multi-line basic string reads \ as an escape and """ as its end, so both are
    # escaped: the role decodes to exactly the persona text.
    printf 'developer_instructions = """\n'
    persona_prompt "$p" | sed -e 's/\\/\\\\/g' -e 's/"""/""\\"/g'
    printf '"""\n'
    # Web: the built-in `web_search` tool is on by default (enabled at config level,
    # not per-role — see config block below). ORCHESTRATE_WEB_MCP escape hatch: if set,
    # wire that MCP server name for the researcher instead. (mcp_servers is a MAP table,
    # [mcp_servers.<name>].) Table header LAST.
    if [ "$web" = true ] && [ -n "$WEB_MCP" ]; then
      printf '[mcp_servers.%s]\n# command/args for your web/doc MCP go here (escape hatch; built-in web_search is the default).\n' "$WEB_MCP"
    fi
  } > "$AGENTS_DEST/$p.toml"
  echo "  subagent -> $AGENTS_DEST/$p.toml   (sandbox: $sandbox, model: ${model:-inherit}, effort: ${effort:-inherit}, web: $web)"
done

cat <<EOF

Codex install complete ($SCOPE scope).
  subagents -> $AGENTS_DEST/{...}.toml
  skill     -> $SKILL_DEST/  (SKILL.md + references/ + runtime/; codex auto-discovers
               .agents/skills: invoke \$orchestrate or let the description trigger; ADR-0034)

No hooks, no config.toml edits. Web is built in (web_search, on by default); set
ORCHESTRATE_WEB_MCP ONLY to wire a custom web/doc MCP as an escape hatch. Set
HELDOUT_ROOT, then run /orchestrate to start or resume. Codex spawns subagents only on
explicit request; agents.max_depth defaults to 1.
Ledger: .agents/runs/orchestrate/board.jsonl.
EOF
